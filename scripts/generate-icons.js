function createIcon(size) {
  const buf = Buffer.from(basePng)
  // PNG IHDR: width at bytes 16-19, height at bytes 20-23 (big-endian)
  buf.writeUInt32BE(size, 16)
  buf.writeUInt32BE(size, 20)
  return buf
}

const sizes = [48, 72, 96, 128, 152, 192, 384, 512]

try {
  for (const size of sizes) {
    const filename = `icon-${size}.png`
    const filepath = path.join(outDir, filename)
    fs.writeFileSync(filepath, createIcon(size))
    console.log(`✓ ${filename} (${size}×${size})`)
  }
  console.log(`\n✓ All ${sizes.length} icons generated successfully`)
} catch (err) {
  console.error('Error writing icons:', err.message)
  process.exit(1)
}
